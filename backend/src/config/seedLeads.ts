export const seedProviderLeads = async (): Promise<number> => {
  let seededCount = 0;
  for (const lead of authenticResearchedLeads) {
    await ProviderLead.findOneAndUpdate(
      { businessName: lead.businessName, city: lead.city },
      { $setOnInsert: lead },
      { upsert: true, new: true }
    );
    seededCount++;
  }
  return seededCount;
};
